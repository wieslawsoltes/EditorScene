import assert from 'node:assert/strict';
import path from 'node:path';
import {checkDiagnosticGrid} from './browser-diagnostics.mjs';

export async function checkWorkspace({page,state,wait,textIs,paste,click,fill,command,focusEditor,output,checks}) {
  await command('File','New');
  const invalid='class C\n{\n    int X = "wrong";\n}\n';
  await paste(invalid);
  await wait(()=>globalThis.__editorSceneState?.Diagnostics.some(d=>d.startsWith('CS0029:')));
  if(!(await state()).ToolPaneOpen)await click('Error List');
  await wait(()=>globalThis.__editorSceneState?.ToolPaneOpen&&globalThis.__editorSceneState.DiagnosticRowCount>0);
  await fill('Filter diagnostics','CS0029');
  await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===1&&globalThis.__editorSceneState.DiagnosticRenderedTexts.includes('CS0029'));
  await page.screenshot({path:path.join(output,'classic-diagnostics.png')});
  checks.push('Native tabular diagnostics render bound code/position/message cells and filter without editing the document');
  await click('Show errors');await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===0);
  await click('Show errors');await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===1);
  const bounds=(await state()).Controls['Diagnostic rows'];
  await page.mouse.click(bounds[0]+Math.min(220,bounds[2]/2),bounds[1]+12);
  await wait(()=>globalThis.__editorSceneState?.SelectionLength>0&&globalThis.__editorSceneState.TextPrefix.slice(globalThis.__editorSceneState.SelectionStart,globalThis.__editorSceneState.SelectionStart+globalThis.__editorSceneState.SelectionLength).includes('wrong'));
  await textIs(invalid);checks.push('Error severity toggles and actual row clicks navigate the current immutable diagnostic range');
  await command('File','New');
  await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===0&&globalThis.__editorSceneState.AnalysisRevision===globalThis.__editorSceneState.Revision);
  await fill('Filter diagnostics','');
  await wait(()=>globalThis.__editorSceneState?.DiagnosticGrid.FilterText==='' && globalThis.__editorSceneState.DiagnosticGrid.ClearEnabled===false);
  await click('Error List');await wait(()=>globalThis.__editorSceneState?.ToolPaneOpen===false);
  checks.push('Switching documents clears old diagnostic rows even when the new document has the same revision');
  const sample='using System;\nclass Monitor\n{\n    public void Tick()\n    {\n        Console.WriteLine("EditorScene");\n    }\n}\n';
  await paste(sample);await wait(()=>globalThis.__editorSceneState?.AnalysisRevision===globalThis.__editorSceneState.Revision);
  await page.keyboard.press('Control+Home');await page.keyboard.press('ArrowDown');await page.keyboard.press('Home');
  await wait(()=>globalThis.__editorSceneState?.StatusPosition.includes('Ln 2')&&globalThis.__editorSceneState.StatusPosition.includes('Ch 1'));
  let s=await state();const projections=s.DiagnosticProjectionBuilds;
  for(let i=0;i<8;i++){await page.keyboard.press('ArrowRight');await page.keyboard.press('ArrowLeft');}
  await wait(()=>globalThis.__editorSceneState?.CaretOffset===14);
  assert.equal((await state()).DiagnosticProjectionBuilds,projections);
  checks.push('Caret movement uses line-local status positions and does not rebuild diagnostic projections');
  if(!(await state()).ReadOnly)await command('View','Read Only');
  if(!(await state()).WordWrap)await command('View','Word Wrap');
  await command('Window','Split Horizontally');
  await wait(()=>globalThis.__editorSceneState?.Split&&globalThis.__editorSceneState.SplitOrientation==='Vertical'&&globalThis.__editorSceneState.SecondaryReadOnly&&globalThis.__editorSceneState.SecondaryWordWrap&&globalThis.__editorSceneState.OpenMenuCount===0);
  await click('Split separator');
  await wait(()=>globalThis.__editorSceneState?.FocusedControl==='Microsoft.UI.Xaml.Controls.Primitives.Thumb');
  s=await state();let first=s.Controls['Primary editor'],second=s.Controls['Secondary editor'];
  assert.ok(second[1]>first[1]+first[3]-2&&Math.abs(second[0]-first[0])<2,'Expected top/bottom panes');
  let divider=s.Controls['Split separator'];const initial=s.SplitRatio;
  await page.mouse.move(divider[0]+divider[2]/2,divider[1]+divider[3]/2);await page.mouse.down();
  await page.mouse.move(divider[0]+divider[2]/2,divider[1]+divider[3]/2+45,{steps:8});await page.mouse.up();
  await wait(r=>globalThis.__editorSceneState?.SplitRatio>r+.03,initial);
  await click('Split separator');
  await wait(()=>globalThis.__editorSceneState?.FocusedControl==='Microsoft.UI.Xaml.Controls.Primitives.Thumb'&&globalThis.__editorSceneState.OpenMenuCount===0);
  const beforeKey=(await state()).SplitRatio;await page.keyboard.press('ArrowDown');
  await wait(r=>globalThis.__editorSceneState?.SplitRatio>r,beforeKey);
  checks.push('Horizontal native split copies read-only/wrap settings and resizes through both real dragging and arrow keys');
  second=(await state()).Controls['Secondary editor'];await page.mouse.click(second[0]+100,second[1]+20);await page.keyboard.type('BLOCKED');await textIs(sample);
  await command('Window','Split Vertically');
  await wait(()=>globalThis.__editorSceneState?.SplitOrientation==='Horizontal'&&globalThis.__editorSceneState.OpenMenuCount===0);
  s=await state();first=s.Controls['Primary editor'];second=s.Controls['Secondary editor'];
  assert.ok(second[0]>first[0]+first[2]-2&&Math.abs(second[1]-first[1])<2,'Expected side-by-side panes');
  await command('Window','Center Split');await wait(()=>globalThis.__editorSceneState?.SplitRatio===.5&&globalThis.__editorSceneState.OpenMenuCount===0);
  await click('Theme');await click('Choice Light');await wait(()=>globalThis.__editorSceneState?.Theme==='Light');
  await page.screenshot({path:path.join(output,'classic-split-light.png')});
  checks.push('Changing split orientation and centering preserve shared text and read-only input protection');
  await click('Editor zoom');await page.keyboard.press('ArrowRight');
  await wait(()=>globalThis.__editorSceneState?.FontSize!==13);
  await click('Reset zoom');await wait(()=>globalThis.__editorSceneState?.FontSize===13);
  await click('Insert or overwrite');await wait(()=>globalThis.__editorSceneState?.OverwriteMode);
  await click('Insert or overwrite');await wait(()=>globalThis.__editorSceneState?.OverwriteMode===false);
  checks.push('Native status slider, reset percentage and insert/overwrite button control the active view');
  await command('Window','Split Editor');await wait(()=>globalThis.__editorSceneState?.Split===false);
  if((await state()).ReadOnly)await command('View','Read Only');
  if((await state()).WordWrap)await command('View','Word Wrap');
  await click('Theme');await click('Choice Dark');await wait(()=>globalThis.__editorSceneState?.Theme==='Dark');
  await page.screenshot({path:path.join(output,'classic-editor-dark.png')});
  await findThroughOverflow('classic-toolbar-overflow.png');
  checks.push('Toolbar overflow exposes real commands while the compact workspace retains the current editor document');
  const originalViewport=page.viewportSize();
  await page.setViewportSize({width:640,height:700});
  await wait(()=>globalThis.__editorSceneState?.Controls?.['Toolbar commands']?.[0]<640);
  await findThroughOverflow('classic-toolbar-overflow-narrow.png');
  checks.push('All seven toolbar overflow groups and their Search commands remain on screen in a narrow workspace');
  await page.setViewportSize(originalViewport);
  await wait(()=>globalThis.__editorSceneState?.Controls?.['Toolbar commands']?.[0]>640);
  await focusEditor();
  await checkDiagnosticGrid({page,state,wait,textIs,paste,click,fill,command,focusEditor,output,checks});

  async function findThroughOverflow(screenshot) {
    await click('Toolbar commands');
    await wait(()=>!!globalThis.__editorSceneState?.Controls?.['Visible submenu Search']);
    const viewport=page.viewportSize();
    const groups=Object.entries((await state()).Controls).filter(([name])=>name.startsWith('Visible submenu '));
    assert.equal(groups.length,7,'Toolbar overflow must contain seven bounded command groups');
    for(const [name,b] of groups) assert.ok(b[0]>=0&&b[1]>=0&&b[0]+b[2]<=viewport.width+1&&b[1]+b[3]<=viewport.height+1,`${name} must be inside the viewport`);
    await click('Visible submenu Search');
    await wait(()=>!!globalThis.__editorSceneState?.Controls?.['Visible command Find']);
    const findBounds=(await state()).Controls['Visible command Find'];
    assert.ok(findBounds[0]>=0&&findBounds[1]>=0&&findBounds[0]+findBounds[2]<=viewport.width+1&&findBounds[1]+findBounds[3]<=viewport.height+1,'Find must be on screen before actual pointer input');
    await page.screenshot({path:path.join(output,screenshot)});
    await click('Visible command Find');await wait(()=>globalThis.__editorSceneState?.SearchOpen);
    await click('PART_close');await focusEditor();await textIs(sample);
  }
}
