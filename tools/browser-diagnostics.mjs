import assert from 'node:assert/strict';
import path from 'node:path';

// Uses only pointer, keyboard and clipboard input against the published native app.
export async function checkDiagnosticGrid({page,state,wait,textIs,paste,click,fill,command,focusEditor,output,checks}) {
  await command('File','New');
  const text='class Broken\n{\n    void M()\n    {\n'+Array.from({length:300},(_,i)=>`        U${String(i).padStart(3,'0')}();\n`).join('')+'    }\n}\n';
  assert.ok(text.length<8192,'Fixture must fit the existing read-only text observation bound');
  await paste(text);
  await wait(()=>globalThis.__editorSceneState?.AnalysisRevision===globalThis.__editorSceneState.Revision&&globalThis.__editorSceneState.Diagnostics.length===300);
  if(!(await state()).ToolPaneOpen)await click('Error List');
  await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===300&&globalThis.__editorSceneState.DiagnosticGrid.RealizedRows>0&&globalThis.__editorSceneState.DiagnosticRenderedTexts.includes('CS0103'));
  let s=await state();
  assert.ok(s.DiagnosticGrid.RealizedRows<120,'A 300-row table must not construct all native row presenters');
  assert.ok(s.DiagnosticGrid.RowIcons.length>0&&s.DiagnosticGrid.RowIcons.every(k=>k==='Error'),'Realized rows must use the native original Error vector');
  assert.ok(s.DiagnosticRenderedTexts.includes(s.FileName),'The actual file column must render');
  checks.push('Compiled diagnostic templates render filenames and severity vectors while virtualizing a 300-error document');
  const highest=Math.max(...s.DiagnosticGrid.VisibleLines);
  await click('Sort diagnostics by Line');
  await wait(()=>globalThis.__editorSceneState?.DiagnosticGrid.SortColumn==='Line'&&globalThis.__editorSceneState.DiagnosticGrid.SortDirection==='Ascending');
  await click('Sort diagnostics by Line');
  await wait(n=>globalThis.__editorSceneState?.DiagnosticGrid.SortDirection==='Descending'&&globalThis.__editorSceneState.DiagnosticGrid.VisibleLines[0]===n,highest);
  s=await state();
  assert.deepEqual(s.DiagnosticGrid.VisibleLines,[...s.DiagnosticGrid.VisibleLines].sort((a,b)=>b-a));
  const projections=s.DiagnosticProjectionBuilds,sorts=s.DiagnosticGrid.SortBuilds;
  await fill('Filter diagnostics','U299');await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===1);
  assert.equal((await state()).DiagnosticGrid.SortBuilds,sorts,'Filtering must reuse the current immutable ordering');
  await click('Clear diagnostic filter');await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===300);
  assert.equal((await state()).DiagnosticGrid.SortBuilds,sorts);
  checks.push('Native headers sort line numbers numerically in both directions and filtering reuses the ordering');
  await click('Resize diagnostic Code');
  await wait(()=>globalThis.__editorSceneState?.FocusedControl==='Microsoft.UI.Xaml.Controls.Primitives.Thumb');
  s=await state();const grip=s.Controls['Resize diagnostic Code'],width=s.DiagnosticGrid.Widths[1];
  await page.mouse.move(grip[0]+grip[2]/2,grip[1]+grip[3]/2);await page.mouse.down();
  await page.mouse.move(grip[0]+grip[2]/2+42,grip[1]+grip[3]/2,{steps:7});await page.mouse.up();
  await wait(w=>globalThis.__editorSceneState?.DiagnosticGrid.Widths[1]>w+30,width);
  await wait(()=>{const g=globalThis.__editorSceneState?.DiagnosticGrid;return g?.RowWidths.length>0&&g.RowWidths.every(w=>Math.abs(w[1]-g.Widths[1])<.01);});
  await click('Resize diagnostic Code');const dragged=(await state()).DiagnosticGrid.Widths[1];await page.keyboard.press('ArrowLeft');
  await wait(w=>globalThis.__editorSceneState?.DiagnosticGrid.Widths[1]<w,dragged);
  await page.keyboard.press('Home');await wait(()=>globalThis.__editorSceneState?.DiagnosticGrid.Widths[1]===82);
  s=await state();assert.equal(s.DiagnosticGrid.SortBuilds,sorts);assert.equal(s.DiagnosticProjectionBuilds,projections);
  checks.push('Real column dragging, keyboard adjustment and Home reset update realized rows without sorting or projecting data');
  const target=s.DiagnosticGrid.VisibleOffsets[0],rows=s.Controls['Diagnostic rows'];
  await page.mouse.click(rows[0]+180,rows[1]+12);
  await wait(offset=>globalThis.__editorSceneState?.SelectionStart===offset&&globalThis.__editorSceneState.SelectionLength>0,target);
  await textIs(text);
  await focusEditor();await page.keyboard.press('ArrowLeft');await page.keyboard.press('ArrowRight');
  assert.equal((await state()).DiagnosticGrid.SortBuilds,sorts);assert.equal((await state()).DiagnosticProjectionBuilds,projections);
  checks.push('Clicking a sorted diagnostic navigates its current source range without mutating or rebuilding the document');
  await click('Theme');await click('Choice Light');await wait(()=>globalThis.__editorSceneState?.Theme==='Light');
  await page.screenshot({path:path.join(output,'diagnostic-grid-light.png')});
  const originalViewport=page.viewportSize();await page.setViewportSize({width:640,height:700});
  await wait(()=>globalThis.__editorSceneState?.DiagnosticGrid.HorizontalExtent>50);
  const beforeScroll=(await state()).Controls['Sort diagnostics by Code'][0];
  const narrowRows=(await state()).Controls['Diagnostic rows'];
  await page.mouse.move(Math.min(400,narrowRows[0]+180),narrowRows[1]+30);await page.mouse.wheel(480,0);
  await wait(()=>globalThis.__editorSceneState?.DiagnosticGrid.HorizontalOffset>20);
  assert.ok((await state()).Controls['Sort diagnostics by Code'][0]<beforeScroll-10,'Headers must move with the horizontally scrolled rows');
  await page.screenshot({path:path.join(output,'diagnostic-grid-narrow.png')});
  await page.mouse.wheel(-2000,0);await wait(()=>globalThis.__editorSceneState?.DiagnosticGrid.HorizontalOffset<2);
  await page.setViewportSize(originalViewport);await click('Reset diagnostic columns and order');
  await wait(()=>globalThis.__editorSceneState?.DiagnosticGrid.SortColumn==='ProviderOrder');
  await click('Theme');await click('Choice Dark');await wait(()=>globalThis.__editorSceneState?.Theme==='Dark');
  await page.screenshot({path:path.join(output,'diagnostic-grid-dark.png')});
  checks.push('Diagnostic headers and rows scroll together at narrow widths and the native reset restores provider ordering');
  await command('File','New');
  await wait(()=>globalThis.__editorSceneState?.DiagnosticRowCount===0&&globalThis.__editorSceneState.DiagnosticGrid.RealizedRows===0);
  await click('Error List');await wait(()=>globalThis.__editorSceneState?.ToolPaneOpen===false);await focusEditor();
  checks.push('Switching away from a large diagnostic table releases its realized row ownership and stale query state');
}
